import test from "node:test";
import assert from "node:assert/strict";

import {
  createDevelopmentProposalProvider,
  createProposalWorkspaceAdapter,
  validateDevelopmentProposal,
  DEVELOPMENT_PROPOSAL_LIMITS
} from "../providers/developmentProposalProvider.js";

const allowedPaths = ["development/example"];

test("proposal validation accepts scoped text files", () => {
  const result = validateDevelopmentProposal({
    summary: "Improve a test world asset.",
    files: [
      { path: "development/example/world.js", content: "export const ready = true;" }
    ]
  }, { allowedPaths });

  assert.equal(result.files.length, 1);
  assert.equal(result.files[0].path, "development/example/world.js");
  assert.equal(result.summary, "Improve a test world asset.");
});

test("proposal validation rejects traversal and paths outside the allowlist", () => {
  for (const path of [
    "../secrets.txt",
    "development/example/../../secrets.txt",
    "development/other/world.js",
    ".git/config",
    "development/example\\world.js"
  ]) {
    assert.throws(
      () => validateDevelopmentProposal({
        summary: "Unsafe proposal",
        files: [{ path, content: "no" }]
      }, { allowedPaths }),
      /Unsafe|outside|protected/
    );
  }
});

test("proposal validation rejects duplicate paths and empty proposals", () => {
  assert.throws(
    () => validateDevelopmentProposal({
      summary: "Duplicate",
      files: [
        { path: "development/example/a.js", content: "a" },
        { path: "development/example/a.js", content: "b" }
      ]
    }, { allowedPaths }),
    /duplicate/
  );

  assert.throws(
    () => validateDevelopmentProposal({ summary: "Empty", files: [] }, { allowedPaths }),
    /at least one file/
  );
});

test("proposal validation enforces file-count and content-size limits", () => {
  const tooMany = Array.from(
    { length: DEVELOPMENT_PROPOSAL_LIMITS.maxFiles + 1 },
    (_, index) => ({
      path: `development/example/file-${index}.txt`,
      content: "x"
    })
  );

  assert.throws(
    () => validateDevelopmentProposal({ summary: "Too many", files: tooMany }, { allowedPaths }),
    /file limit/
  );

  assert.throws(
    () => validateDevelopmentProposal({
      summary: "Too large",
      files: [{
        path: "development/example/large.txt",
        content: "x".repeat(DEVELOPMENT_PROPOSAL_LIMITS.maxFileBytes + 1)
      }]
    }, { allowedPaths }),
    /size limit/
  );
});

test("provider wrapper validates generated output and passes only scoped paths", async () => {
  let received;
  const proposalProvider = createDevelopmentProposalProvider({
    allowedPaths,
    provider: {
      async generateProposal(input) {
        received = input;
        return {
          summary: "Generated by a mock provider.",
          files: [{ path: "development/example/world.js", content: "export const x = 1;" }]
        };
      }
    }
  });

  const result = await proposalProvider.generateProposal({
    task: { id: "task-1", title: "Improve world" },
    context: { files: [] }
  });

  assert.deepEqual(received.allowedPaths, allowedPaths);
  assert.equal(result.files[0].path, "development/example/world.js");
});

test("proposal workspace adapter applies validated files only inside the isolated workspace", async () => {
  const calls = [];
  const provider = createDevelopmentProposalProvider({
    allowedPaths,
    provider: {
      async generateProposal() {
        return {
          summary: "Add a scoped world detail.",
          files: [{ path: "development/example/world.js", content: "export const detail = true;" }]
        };
      }
    }
  });

  const adapter = createProposalWorkspaceAdapter({
    allowedPaths,
    proposalProvider: provider,
    workspaceAdapter: {
      async createWorkspace(input) {
        calls.push(["createWorkspace", input]);
        return { workspaceId: "isolated-1" };
      },
      async readWorkspaceContext(input) {
        calls.push(["readWorkspaceContext", input]);
        return { currentFiles: [] };
      },
      async applyProposedFiles(input) {
        calls.push(["applyProposedFiles", input]);
      },
      async runTests(input) {
        calls.push(["runTests", input]);
        return { passed: true, total: 2, failed: 0 };
      }
    }
  });

  const workspace = await adapter.createWorkspace({ taskId: "task-1" });
  const proposal = await adapter.prepareChanges({
    workspaceId: workspace.workspaceId,
    task: { id: "task-1", title: "Improve world" }
  });
  const tests = await adapter.runTests({ workspaceId: workspace.workspaceId });

  assert.equal(proposal.changedFiles[0], "development/example/world.js");
  assert.equal(proposal.changes, "Add a scoped world detail.");
  assert.equal(tests.passed, true);
  assert.equal(calls.find(call => call[0] === "applyProposedFiles")[1].files.length, 1);
});

test("proposal workspace adapter refuses to run without isolated workspace methods", () => {
  assert.throws(
    () => createProposalWorkspaceAdapter({
      allowedPaths,
      proposalProvider: { async generateProposal() {} },
      workspaceAdapter: {}
    }),
    /workspaceAdapter.createWorkspace/
  );
});
